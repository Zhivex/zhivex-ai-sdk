// Copy into an isolated consumer of the packed or published packages and run with Bun.
import assert from "node:assert/strict";
import { createTextMessage, googleSearchTool, streamText, toUIMessage } from "@zhivex-ai/core";
import { createQwen, qwenWebSearchTool } from "@zhivex-ai/qwen";
import { createGemini } from "@zhivex-ai/gemini";
const messages = [createTextMessage("user", "Search")];
const citation = { type: "url_citation", url: "https://example.com", title: "Source", start_index: 0, end_index: 6 };
const item = { type: "message", id: "msg_fixture", content: [{ type: "output_text", text: "Source", annotations: [citation] }] };
const sse = events => new Response(events.map(event => `data: ${JSON.stringify(event)}\n\n`).join(""));
const qwen = createQwen({ apiKey: "fixture", fetch: async (url, init) => {
  assert.match(String(url), /\/responses$/);
  const body = JSON.parse(init.body); assert.equal(body.max_output_tokens, 100);
  assert.equal(body.tools[0].type, "web_search");
  const response = { status: "incomplete", output: [item], usage: { input_tokens: 10, output_tokens: 100, total_tokens: 110, x_tools: { web_search: { count: 2 } } } };
  return body.stream ? sse([{ type: "response.output_item.done", output_index: 0, item }, { type: "response.incomplete", response }]) : Response.json(response);
} })("qwen3.8-flash");
const generated = await qwen.generate({ messages, maxTokens: 100, tools: { search: qwenWebSearchTool() } });
assert.equal(generated.finishReason, "length");
assert.equal(generated.messages[0].parts.find(p => p.type === "provider-data" && p.data.type === "hosted-tool-usage").data.quantity, 2);
assert.equal(toUIMessage(generated.messages[0]).parts.some(p => p.type === "provider-data" && p.data.type === "hosted-tool-usage"), false);
const qwenResult = streamText({ model: qwen, messages, maxTokens: 100, tools: { search: qwenWebSearchTool() } });
const qwenEvents = []; for await (const e of qwenResult.eventStream) qwenEvents.push(e);
assert.equal(qwenEvents.filter(e => e.type === "provider-data" && e.data.type === "response.annotations").length, 1);
assert.equal((await qwenResult.collect()).finishReason, "length");
const meter = qwenEvents.filter(e => e.type === "provider-data" && e.data.type === "hosted-tool-usage");
assert.equal(meter.length, 2);
assert.equal(meter[0].data.completeness, "unknown");
assert.equal(meter[1].data.quantity, 2);
const groundingMetadata = { groundingChunks: [{ web: { uri: "https://example.com", title: "Source" } }], groundingSupports: [{ segment: { startIndex: 0, endIndex: 6 }, groundingChunkIndices: [0] }], webSearchQueries: ["query"], searchEntryPoint: { renderedContent: "<div>Google attribution</div>" } };
const gemini = createGemini({ apiKey: "fixture", fetch: async () => sse([{ candidates: [{ content: { parts: [{ text: "Source" }] }, groundingMetadata, finishReason: "STOP" }] }]) })("gemini-3.8-flash");
const geminiResult = streamText({ model: gemini, messages, tools: { search: googleSearchTool() } });
const geminiEvents = []; for await (const e of geminiResult.eventStream) geminiEvents.push(e);
assert.equal(geminiEvents.find(e => e.type === "provider-data" && e.data.type === "grounding-metadata").data.groundingMetadata.groundingChunks[0].web.uri, "https://example.com");
assert.equal((await geminiResult.collect()).text, "Source");
const geminiMeter = geminiEvents.filter(e => e.type === "provider-data" && e.data.type === "hosted-tool-usage");
assert.equal(geminiMeter.at(-1).data.quantity, 1);
assert.equal(geminiMeter.at(-1).data.unit, "query");
assert.equal(JSON.stringify(geminiEvents.filter(e => e.type === "provider-data")).includes('"webSearchQueries"'), false);
console.log(JSON.stringify({ internalMetering: true, publicUIFiltered: true, status: "passed", qwenBoundedGenerate: true, qwenBoundedStream: true, qwenCitationsDeduplicated: true, geminiGroundingCollected: true }));
